// Command gen-tzinfo converts LuCI's zoneinfo table
// (modules/luci-lua-runtime/luasrc/sys/zoneinfo/tzdata.lua in
// https://github.com/openwrt/luci) into internal/tzinfo/table.go.
// Usage: go run ./scripts/gen-tzinfo path/to/tzdata.lua > internal/tzinfo/table.go
package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

var entryRE = regexp.MustCompile(`^\s*\{\s*'([^']+)'\s*,\s*'([^']*)'\s*\}`)

func main() {
	os.Exit(run())
}

// run does the actual work and returns a process exit code. Splitting this
// out of main keeps every os.Exit call outside the scope of the deferred
// f.Close/out.Flush calls below, so they always run before the process exits.
func run() int {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: gen-tzinfo <tzdata.lua>")

		return 1
	}

	// Path comes from the operator's own argv to this build-time generator,
	// not from an untrusted request; gosec's taint check has no way to know
	// that.
	f, err := os.Open(os.Args[1]) //nolint:gosec // operator-supplied CLI arg, not a runtime request
	if err != nil {
		fmt.Fprintln(os.Stderr, err)

		return 1
	}
	defer f.Close()

	out := bufio.NewWriter(os.Stdout)
	defer out.Flush()

	fmt.Fprintln(out, "// Code generated by scripts/gen-tzinfo; DO NOT EDIT.")
	fmt.Fprintln(out, "// Source: OpenWrt LuCI luasrc/sys/zoneinfo/tzdata.lua")
	fmt.Fprintln(out, "")
	fmt.Fprintln(out, "package tzinfo")
	fmt.Fprintln(out, "")
	fmt.Fprintln(out, "//nolint:gochecknoglobals // generated lookup table")
	fmt.Fprintln(out, "var zones = map[string]string{")

	sawUTC := false

	sc := bufio.NewScanner(f)
	for sc.Scan() {
		if m := entryRE.FindStringSubmatch(sc.Text()); m != nil {
			if m[1] == "UTC" {
				sawUTC = true
			}

			fmt.Fprintf(out, "\t%q: %q,\n", m[1], m[2])
		}
	}

	if err := sc.Err(); err != nil {
		fmt.Fprintln(os.Stderr, err)

		return 1
	}

	// LuCI's table has no bare UTC entry; append one unconditionally so
	// tzinfo.Known("UTC") always holds regardless of upstream table changes.
	if !sawUTC {
		fmt.Fprintf(out, "\t%q: %q,\n", "UTC", "UTC0")
	}

	fmt.Fprintln(out, "}")

	return 0
}
